#!/usr/bin/env node
// Regenerate src/lib/particles/webgpu/port.generated.ts — the show's GLSL
// (shaders.ts) ported to WGSL for the WebGPU particle engine (?gpu=webgpu).
//
//   NAGA_BIN=/path/to/naga node scripts/gen-webgpu-port.mjs
//
// naga = wgpu's shader translator (`cargo install naga-cli`). Run this after
// any change to the simulation or draw GLSL; the engine refuses a stale port
// (src/lib/particles/webgpu/port.test.ts names this script when it is stale).
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createJiti } from "jiti";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const jiti = createJiti(import.meta.url, { alias: { "@": join(root, "src") } });
const { portSim, portDraw } = await jiti.import(join(root, "src/lib/particles/webgpu/gl-port.ts"));
const { portSources } = await jiti.import(join(root, "src/lib/particles/webgpu/port-sources.ts"));

const naga = process.env.NAGA_BIN || "naga";
const dir = mkdtempSync(join(tmpdir(), "webgpu-port-"));
function translate(name, stage, glsl) {
  const inp = join(dir, `${name}.${stage}.glsl`);
  const out = join(dir, `${name}.${stage}.wgsl`);
  writeFileSync(inp, glsl);
  try {
    execFileSync(naga, ["--input-kind", "glsl", "--shader-stage", stage, inp, out], { stdio: "pipe" });
  } catch (e) {
    console.error(`naga failed on ${name} (${stage}) — input kept at ${inp}\n${e.stderr?.toString() ?? e}`);
    process.exit(1);
  }
  // validate the WGSL too (the translation is only as good as its output)
  execFileSync(naga, [out], { stdio: "pipe" });
  return readFileSync(out, "utf8");
}
const fields = (l) => l.fields.map((f) => [f.name, typeof f.type === "object" ? `vec4f[${f.type.n}]` : f.type, f.offset]);

const src = portSources();
const sim = portSim(src.sim);
const simWgsl = translate("sim", "compute", sim.stages.compute);
const draws = {};
for (const [variant, s] of Object.entries(src.draw)) {
  const d = portDraw(s.vs, s.fs);
  draws[variant] = {
    hash: d.sourceHash,
    vertex: translate(`draw-${variant}`, "vertex", d.stages.vertex),
    fragment: translate(`draw-${variant}`, "fragment", d.stages.fragment),
    size: d.uniforms.size,
    fields: fields(d.uniforms),
  };
}

const out = `// GENERATED by scripts/gen-webgpu-port.mjs (naga ${execFileSync(naga, ["--version"]).toString().trim()}) — do not edit.
// The show's GLSL (shaders.ts) ported to WGSL for the WebGPU engine; see gl-port.ts.
/* eslint-disable */
export type PortField = [name: string, type: string, offset: number];
export interface PortedSimWgsl { hash: string; wgsl: string; size: number; fields: PortField[] }
export interface PortedDrawWgsl { hash: string; vertex: string; fragment: string; size: number; fields: PortField[] }

export const SIM_PORT: PortedSimWgsl = ${JSON.stringify({ hash: sim.sourceHash, wgsl: simWgsl, size: sim.uniforms.size, fields: fields(sim.uniforms) })};

export const DRAW_PORT: Record<"plain" | "stable", PortedDrawWgsl> = ${JSON.stringify(draws)};
`;
writeFileSync(join(root, "src/lib/particles/webgpu/port.generated.ts"), out);
console.log(`port.generated.ts: sim ${sim.sourceHash} (${Math.round(simWgsl.length / 1024)} KB), draw ${Object.entries(draws).map(([k, v]) => `${k} ${v.hash}`).join(", ")}`);
