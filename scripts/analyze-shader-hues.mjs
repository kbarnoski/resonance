#!/usr/bin/env node
/**
 * analyze-shader-hues.mjs — shader↔palette coordination, stage 1
 * (2026-09-27 review: "colored shaders overlay and clash with colors of
 * what's shown in images — coordinate this so all shaders work well with
 * the imaging they overlay").
 *
 * Statically analyzes every registered shader's GLSL for its dominant hue:
 *   - collects vec3/vec4 color literals, weights by saturation × brightness
 *   - detects procedural hue sweeps (hsv2rgb/hsb2rgb/hue rotation with a
 *     computed hue) → "prismatic"
 *   - low chroma evidence → "neutral"
 *   - wide hue spread (dominant family < 45% of chroma weight) → "prismatic"
 * and writes src/lib/shaders/shader-hues.generated.ts (committed — the
 * selection pipeline and the registry gate consume it).
 *
 * Re-run whenever shaders are added:  node scripts/analyze-shader-hues.mjs
 */
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { rm } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = process.cwd();
const outfile = path.join(ROOT, ".tmp-hue-bundle.mjs");
await build({
  stdin: {
    contents: `export { SHADERS, MODE_META } from "@/lib/shaders";`,
    resolveDir: ROOT,
    loader: "ts",
  },
  bundle: true, format: "esm", platform: "node", packages: "external",
  alias: { "@": path.join(ROOT, "src") },
  outfile,
});
let app;
try { app = await import(pathToFileURL(outfile).href); }
finally { await rm(outfile, { force: true }); }

const FAMILIES = [
  ["ember", 345, 385],   // wraps: 345-360 + 0-25
  ["gold", 25, 70],
  ["green", 70, 160],
  ["teal", 160, 200],
  ["blue", 200, 250],
  ["violet", 250, 305],
  ["magenta", 305, 345],
];
const familyOf = (hue) => {
  const h = ((hue % 360) + 360) % 360;
  for (const [name, lo, hi] of FAMILIES) {
    if (hi > 360 ? (h >= lo || h < hi - 360) : (h >= lo && h < hi)) return name;
  }
  return "ember";
};

function rgbToHsv(r, g, b) {
  const max = Math.max(r, g, b), min = Math.min(r, g, b), d = max - min;
  let h = 0;
  if (d > 0) {
    if (max === r) h = 60 * (((g - b) / d) % 6);
    else if (max === g) h = 60 * ((b - r) / d + 2);
    else h = 60 * ((r - g) / d + 4);
  }
  return { h: ((h % 360) + 360) % 360, s: max === 0 ? 0 : d / max, v: max };
}

const NUM = String.raw`(\d+\.?\d*|\.\d+)`;
const VEC = new RegExp(String.raw`vec[34]\s*\(\s*${NUM}\s*,\s*${NUM}\s*,\s*${NUM}`, "g");
const HSV_LIT = new RegExp(String.raw`(?:hsv2rgb|hsb2rgb|hsl2rgb)\s*\(\s*(?:vec3\s*\(\s*)?${NUM}`, "g");
const HSV_PROC = /(?:hsv2rgb|hsb2rgb|hsl2rgb|hue2rgb|hueShift|rainbow)\s*\(/;

function classify(src) {
  const famWeight = Object.fromEntries(FAMILIES.map(([f]) => [f, 0]));
  let chroma = 0, colors = 0;

  for (const m of src.matchAll(VEC)) {
    const [r, g, b] = [Number(m[1]), Number(m[2]), Number(m[3])];
    if (![r, g, b].every((x) => x >= 0 && x <= 1.6)) continue; // HDR-ish ok, skip UVs > that
    const { h, s, v } = rgbToHsv(Math.min(r, 1), Math.min(g, 1), Math.min(b, 1));
    colors++;
    if (s < 0.18 || v < 0.12) continue; // grey/near-black — not hue evidence
    const w = s * v;
    famWeight[familyOf(h)] += w;
    chroma += w;
  }
  for (const m of src.matchAll(HSV_LIT)) {
    const hue = Number(m[1]);
    const h = hue <= 1.01 ? hue * 360 : hue; // normalized or degrees
    famWeight[familyOf(h)] += 0.8;
    chroma += 0.8;
  }

  const proceduralHue = HSV_PROC.test(src) && !HSV_LIT.test(src);
  if (proceduralHue && chroma < 1.5) return "prismatic";
  if (chroma < 0.35) return "neutral";
  const sorted = Object.entries(famWeight).sort((a, b) => b[1] - a[1]);
  const [topFam, topW] = sorted[0];
  if (topW / chroma < 0.45) return "prismatic";
  return topFam;
}

const hues = {};
const counts = {};
for (const meta of app.MODE_META) {
  if (meta.category === "AI Imagery") continue;
  const src = app.SHADERS[meta.mode];
  if (typeof src !== "string" || src.length < 20) { hues[meta.mode] = "neutral"; continue; }
  const fam = classify(src);
  hues[meta.mode] = fam;
  counts[fam] = (counts[fam] ?? 0) + 1;
}

const sortedModes = Object.keys(hues).sort();
const lines = sortedModes.map((m) => `  "${m}": "${hues[m]}",`).join("\n");
const out = `// GENERATED by scripts/analyze-shader-hues.mjs — do not edit by hand.
// Dominant hue family per shader, from static GLSL color analysis.
// Consumed by pickJourneyShaders (palette-aware selection) and the
// registry gate. Re-run the script when shaders are added.
export type ShaderHueFamily =
  | "ember" | "gold" | "green" | "teal" | "blue" | "violet" | "magenta"
  | "neutral" | "prismatic";

export const SHADER_HUES: Record<string, ShaderHueFamily> = {
${lines}
};
`;
writeFileSync("src/lib/shaders/shader-hues.generated.ts", out);
console.log(`tagged ${sortedModes.length} shaders:`, counts);
