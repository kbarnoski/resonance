#!/usr/bin/env node
// build-particle-profiles.mjs — bakes the compact v2 deep-analysis profile of
// every particle-cast journey into src/lib/journeys/particle-profiles.generated.ts
// so the particle conductor works OFFLINE on the kiosk (no analysis fetch at
// runtime) and casting is reviewable in git.
//
// Usage: node scripts/build-particle-profiles.mjs [journeyId ...]
//   (no args = the ids in PARTICLE_JOURNEYS below — keep in sync with
//    PARTICLE_LEADS in src/lib/journeys/particle-lead.ts)
import { createClient } from "@supabase/supabase-js";
import { readFileSync, writeFileSync } from "node:fs";

const PARTICLE_JOURNEYS = [
  "910e6b62-abb8-40d1-bd31-ccdf6038f122", // Lantern (Vigil)
  "cd517f5a-c4eb-4d50-8a53-044aa668d087", // Stir Crazy — playful / rhythmic
  "bd748991-a67b-41dc-af94-ac3f612a27c4", // Open Jam (Vigil) — dark / brooding
];

const env = Object.fromEntries(
  readFileSync(".env.local", "utf8").split("\n").filter((l) => l.includes("=")).map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).replace(/^"|"$/g, "")]),
);
const sb = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY);
const ids = process.argv.slice(2).length ? process.argv.slice(2) : PARTICLE_JOURNEYS;

const r2 = (x) => (typeof x === "number" ? Math.round(x * 100) / 100 : x);
const out = {};
for (const id of ids) {
  const { data: j, error } = await sb.from("journeys").select("id,name,recording_id,theme,phases").eq("id", id).single();
  if (error || !j) throw new Error(`journey ${id}: ${error?.message}`);
  const { data: an } = await sb.from("analyses").select("summary,events").eq("recording_id", j.recording_id).maybeSingle();
  const s = an?.summary;
  if (!s?.profile) throw new Error(`journey ${j.name}: no v2 profile`);
  const p = s.profile;
  out[id] = {
    name: j.name,
    recordingId: j.recording_id,
    palette: j.theme?.palette ?? null,
    duration: r2(p.duration),
    key: p.key?.detected ?? null,
    climaxTime: r2(p.dynamics?.climaxTime ?? null),
    // journey phase boundaries (s) — travel morphs ride these
    phaseBounds: (j.phases ?? []).slice(1).map((ph) => r2(ph.start * p.duration)),
    quietestTime: r2(p.dynamics?.quietestTime ?? null),
    curve: (p.dynamics?.curve ?? []).map((c) => [r2(c.t), r2(c.intensity)]),
    sections: (p.sections ?? []).map((x) => ({
      start: r2(x.start),
      end: r2(x.end),
      trend: x.trend,
      intensity: r2(x.intensity),
      onsetRate: r2(x.onsetRate),
      localKey: x.localKey ?? null,
      major: r2(x.chordShare?.major ?? 0),
      minor: r2(x.chordShare?.minor ?? 0),
      suspended: r2(x.chordShare?.suspended ?? 0),
      diminished: r2(x.chordShare?.diminished ?? 0),
      centerMidi: x.register?.centerMidi ?? null,
      brightnessHz: x.brightnessHz ?? null,
    })),
    mood: { words: s.mood?.words ?? [], arousal: r2(s.mood?.arousal ?? 0.5), valence: r2(s.mood?.valence ?? 0) },
    tempo: {
      bpm: r2(s.tempo?.bpm ?? 80),
      feel: s.tempo?.feel ?? "moderate",
      steadiness: r2(s.tempo?.steadiness ?? 0.5),
      pulseClarity: r2(s.tempo?.pulse_clarity ?? 0.3),
      onsetRate: r2(s.tempo?.onset_rate ?? 3),
    },
  };
  console.log(`${j.name}: ${out[id].sections.length} sections, ${out[id].duration}s, climax ${out[id].climaxTime}s`);
}

const body = `// GENERATED by scripts/build-particle-profiles.mjs — do not edit by hand.
// Compact v2 deep-analysis profiles for particle-cast journeys (offline-safe).
import type { ParticleProfile } from "./particle-casting";

export const PARTICLE_PROFILES: Readonly<Record<string, ParticleProfile>> = ${JSON.stringify(out, null, 2).replace(/\[\s+(-?[\d.]+),\s+(-?[\d.]+)\s+\]/g, "[$1, $2]")};
`;
writeFileSync("src/lib/journeys/particle-profiles.generated.ts", body);
console.log(`wrote ${Object.keys(out).length} profiles`);
